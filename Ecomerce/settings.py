def environment_value(name, default=""):
    value = os.environ.get(name)
    if value:
        return value

    if os.name == "nt":
        import winreg
        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, r"Environment") as environment_key:
            try:
                return winreg.QueryValueEx(environment_key, name)[0]
            except FileNotFoundError:
                pass

    return default


